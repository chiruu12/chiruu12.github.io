def show(name, frame):
    print(f"--- {name} ({len(frame[0])}x{len(frame)}) ---")
    print("   " + "".join(str(i % 10) for i in range(len(frame[0]))))
    for i, row in enumerate(frame):
        print(f"{i:2} {row}")
    print()


def shadows(frame):
    out = []
    for y, row in enumerate(frame):
        for x, ch in enumerate(row):
            if ch == "#":
                out.append(f"{x*PX}px {y*PX}px 0 0 var(--pet-color)")
    return ",\n    ".join(out)


def rule(sel, frame):
    return f"{sel} {{\n  box-shadow:\n    {shadows(frame)};\n}}\n"


def shadow_block(frame, indent="      "):
    return (",\n" + indent).join(
        f"{x*PX}px {y*PX}px 0 0 var(--pet-color)"
        for y, row in enumerate(frame) for x, ch in enumerate(row) if ch == "#"
    )


if __name__ == "__main__":
    for n, f in [("WALK_A", WALK_A), ("WALK_B", WALK_B), ("SIT", SIT), ("SIT_BLINK", SIT_BLINK), ("SLEEP", SLEEP)]:
        show(n, f)
    css = []
    css.append("/* generated by genpet.py - do not hand-edit pixel lists */")
    css.append(f".s-walk {{\n  box-shadow: {shadow_block(WALK_A, '    ')};\n}}")
    css.append(f"@keyframes walk-frames {{\n  0%, 49.99% {{ box-shadow: {shadow_block(WALK_A, '      ')}; }}\n  50%, 100% {{ box-shadow: {shadow_block(WALK_B, '      ')}; }}\n}}")
